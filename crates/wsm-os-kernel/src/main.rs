fn kernel_main(boot_info: &'static mut BootInfo) -> ! {
    // Provision physical-memory translation. The bootloader config requests
    // a dynamic mapping; if it is absent, MMIO paths must fail closed instead
    // of assuming identity mapping. WSM_OS_FORCE_NO_PHYS_MAP is a deliberate
    // mutation used by the fail-closed witness to prove the MMIO path refuses
    // to run without a bootloader-provisioned mapping.
    let mapping = if option_env!("WSM_OS_FORCE_NO_PHYS_MAP").is_some() {
        PhysMemMapping::Unavailable
    } else {
        match boot_info.physical_memory_offset.into_option() {
            Some(offset) => PhysMemMapping::Offset(offset),
            None => PhysMemMapping::Unavailable,
        }
    };
    unsafe {
        PHYS_MEM_MAPPING = mapping;
    }
    serial_init();
    serial_write(b"WSM-OS BOOT schema=1 arch=x86_64 status=ok\n");

    let heap = core::ptr::addr_of_mut!(HEAP).cast::<MaybeUninit<ConsCell>>();
    let closures = core::ptr::addr_of_mut!(CLOSURES).cast::<MaybeUninit<ClosureDescriptor>>();
    // SAFETY: HEAP is a private, aligned, fixed-size arena used only by this
    // single-threaded boot witness for the lifetime of the context.
    let mut context = unsafe {
        RuntimeContext::new_with_closures(
            heap,
            HEAP_CAPACITY,
            closures,
            CLOSURE_CAPACITY,
            kernel_failure,
        )
    };
    // SAFETY: fixture.o is generated by the pinned CML revision, its committed
    // manifest exports exactly wsm_entry and admits only the wsm_* ABI imports.
    let result = unsafe { wsm_entry(&mut context) };

    let fixture_name = option_env!("WSM_FIXTURE").unwrap_or("fixture");
    if fixture_name == "fs-fixture" {
        if fs_fixture_witness(&mut context) {
            serial_write(
                b"WSM-OS FS schema=1 format=wsm-fs-records value=(hello world) status=ok\n",
            );
            serial_write(b"WSM-OS BLOCK schema=1 medium=guest-memory block=0 read=ok write=ok flush=ok status=ok\n");
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS FS schema=1 error=invalid-record status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "repl-fixture" {
        repl_fixture(&mut context);
    } else if fixture_name == "gop-repl-fixture" {
        gop_repl_fixture(boot_info, &mut context);
    } else if fixture_name == "m5a-fixture" {
        if is_m5a_fixture_result(result, &context) {
            serial_write(b"WSM-OS RESULT schema=1 value=(40 . t) status=ok\n");
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "m5b-success-fixture" {
        if is_m5b_success_fixture_result(result, &context) {
            serial_write(b"WSM-OS RESULT schema=1 value=(1152921504606846975 . -1152921504606846976) status=ok\n");
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "m5b-overflow-fixture" {
        // We shouldn't reach here because wsm_fail triggers a kernel_failure trap.
        serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
        qemu_exit(0x12)
    } else if fixture_name == "m5c-tail-call-fixture" {
        // The shared-oracle lane is an observer, not an expected-value oracle.
        // It serializes only already-ratified bounded target representations;
        // the upstream my-lisp corpus owns the expected semantic value.
        if emit_bounded_oracle_observation(result) {
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=unsupported-observation status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "m1-identity-lambda-fixture" {
        if result == wsm_os_target::encode_fixnum(7).unwrap() {
            serial_write(b"WSM-OS RESULT schema=1 value=7 execution=machine-call status=ok\n");
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "m1-lexical-lambda-fixture" {
        if is_m1_lexical_lambda_result(result, &context) {
            serial_write(b"WSM-OS RESULT schema=1 value=(A) execution=lexical-frame status=ok\n");
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "m1-captured-lambda-fixture" {
        if is_m1_captured_lambda_result(result, &context) {
            serial_write(
                b"WSM-OS RESULT schema=1 value=(A B) execution=captured-frame status=ok\n",
            );
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "m2-escaping-closure-fixture" {
        if is_m1_captured_lambda_result(result, &context) {
            serial_write(
                b"WSM-OS RESULT schema=1 value=(A B) execution=escaping-closure status=ok\n",
            );
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
            qemu_exit(0x12)
        }
    } else if fixture_name == "d0-virtio-identity-fixture" {
        if result == wsm_os_target::CANONICAL_T {
            serial_write(
                b"WSM-OS DRIVER schema=1 driver=virtio-blk stage=identity value=t execution=wsm status=ok\n",
            );
            qemu_exit(0x10)
        } else {
            serial_write(
                b"WSM-OS DRIVER schema=1 driver=virtio-blk stage=identity error=unexpected-value status=error\n",
            );
            qemu_exit(0x12)
        }
    } else if fixture_name == "d1-pci-config-capability-fixture" {
        if result == wsm_os_target::CANONICAL_T {
            serial_write(
                b"WSM-OS DRIVER schema=1 driver=virtio-blk stage=pci-config value=t execution=wsm status=ok\n",
            );
            qemu_exit(0x10)
        } else {
            serial_write(
                b"WSM-OS DRIVER schema=1 driver=virtio-blk stage=pci-config error=unexpected-value status=error\n",
            );
            qemu_exit(0x12)
        }
    } else if fixture_name == "d1-pci-config-bounds-fixture" {
        // A bounded capability violation must have trapped through wsm_fail.
        serial_write(b"WSM-OS DRIVER schema=1 driver=virtio-blk stage=pci-config error=missing-condition status=error\n");
        qemu_exit(0x12)
    } else if fixture_name == "d2-virtio-blk-status-fixture" {
        if result == wsm_os_target::CANONICAL_T {
            serial_write(
                b"WSM-OS DRIVER schema=1 driver=virtio-blk stage=mmio-status value=t execution=wsm status=ok\n",
            );
            qemu_exit(0x10)
        } else {
            serial_write(
                b"WSM-OS DRIVER schema=1 driver=virtio-blk stage=mmio-status error=unexpected-value status=error\n",
            );
            qemu_exit(0x12)
        }
    } else {
        if is_first_fixture_result(result, &context) {
            serial_write(b"WSM-OS RESULT schema=1 value=(A . B) status=ok\n");
            qemu_exit(0x10)
        } else {
            serial_write(b"WSM-OS RESULT schema=1 error=abi-violation status=error\n");
            qemu_exit(0x12)
        }
    }
}

const FS_RECORDS: &[u8] = include_bytes!("../../../artifacts/fs-qemu-records.txt");

fn fs_fixture_witness(context: &mut RuntimeContext) -> bool {
    let mut medium = guest_block::GuestBlockMedium::new();
    if !medium.write(FS_RECORDS) || !medium.read_matches(FS_RECORDS) || !medium.flush() {
        return false;
    }
    let Ok(stream) = fs_records::parse(FS_RECORDS) else {
        return false;
    };
    if fs_records::reconstruct_root(&stream).is_err() {
        return false;
    }
    if stream.count != 3
        || stream.records[0].map(|record| record.kind) != Some(fs_records::RecordKind::Root)
        || stream.records[1].map(|record| record.kind) != Some(fs_records::RecordKind::Object)
    {
        return false;
    }
    let hello = wsm_os_target::encode_symbol(1).unwrap();
    let world = wsm_os_target::encode_symbol(2).unwrap();
    let Ok(tail) = context.cons(world, wsm_os_target::NIL) else {
        return false;
    };
    let Ok(root) = context.cons(hello, tail) else {
        return false;
    };
    let Ok(root_cell) = context.cell(root) else {
        return false;
    };
    let Ok(tail_cell) = context.cell(root_cell.cdr) else {
        return false;
    };
    decode_symbol(root_cell.car) == Some(1)
        && decode_symbol(tail_cell.car) == Some(2)
        && tail_cell.cdr == wsm_os_target::NIL
}

