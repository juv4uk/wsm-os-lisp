use wsm_os_target::{
    decode_capability_descriptor, encode_capability_descriptor, CapabilityDescriptor,
    CapabilityKind,
};

const PCI_CONFIG_ADDRESS: u16 = 0xcf8;
const PCI_CONFIG_DATA: u16 = 0xcfc;

/// Active capability entry in the substrate registry.
#[derive(Clone, Copy)]
struct CapabilityGrant {
    kind: CapabilityKind,
    instance: u8,
    nonce: Word,
    active: bool,
}

const MAX_CAPABILITY_GRANTS: usize = 4;
static mut CAPABILITY_REGISTRY: [CapabilityGrant; MAX_CAPABILITY_GRANTS] = [CapabilityGrant {
    kind: CapabilityKind::PciConfig,
    instance: 0,
    nonce: 0,
    active: false,
};
    MAX_CAPABILITY_GRANTS];

/// Physical-memory translation provisioned by the bootloader.
/// virtual = physical + offset. `Unavailable` means the bootloader did NOT
/// provide the requested dynamic mapping: any MMIO path must fail closed
/// instead of assuming identity mapping (offset zero is not proof of a
/// mapping being present).
#[derive(Clone, Copy)]
enum PhysMemMapping {
    Unavailable,
    Offset(u64),
}

static mut PHYS_MEM_MAPPING: PhysMemMapping = PhysMemMapping::Unavailable;

/// MMIO substrate failure codes. Distinct from WSM semantic/runtime
/// conditions: these are raised by the platform provider itself.
const MMIO_ERR_MAPPING_UNAVAILABLE_READ: u32 = 0x4D49_4F07;
const MMIO_ERR_MAPPING_UNAVAILABLE_WRITE: u32 = 0x4D49_4F08;
const MMIO_ERR_ADDRESS_OVERFLOW_READ: u32 = 0x4D49_4F09;
const MMIO_ERR_ADDRESS_OVERFLOW_WRITE: u32 = 0x4D49_4F0A;

/// Physical base address of the virtio-blk VirtIO common-config MMIO region.
/// Resolved once by walking the PCI capability list for BDF 00:05.0.
static mut MMIO_COMMON_CFG_PHYS: u64 = 0;

/// Hardware/boot-provisioned provenance nonce for PCI config capability.
/// Boot nonces are non-zero tokens verified by privileged gates (max 45 bits).
const PCI_CONFIG_BOOT_NONCE: Word = 0x1504_3495_4346; // 45-bit valid nonce

fn init_pci_config_grant() -> Word {
    unsafe {
        let registry = core::ptr::addr_of_mut!(CAPABILITY_REGISTRY);
        (*registry)[0] = CapabilityGrant {
            kind: CapabilityKind::PciConfig,
            instance: 0,
            nonce: PCI_CONFIG_BOOT_NONCE,
            active: true,
        };
    }
    let desc = CapabilityDescriptor::new(CapabilityKind::PciConfig, 0, PCI_CONFIG_BOOT_NONCE)
        .expect("PCI config descriptor must be valid");
    encode_capability_descriptor(desc).expect("PCI config capability must encode")
}

fn verify_capability_grant(
    capability: Word,
    expected_kind: CapabilityKind,
    expected_instance: u8,
) -> bool {
    // Structural decode: a capability must carry the current descriptor
    // shape. Legacy numeric IDs are representation history, not authority.
    let Some(desc) = decode_capability_descriptor(capability) else {
        return false;
    };

    if desc.kind != expected_kind || desc.instance != expected_instance {
        return false;
    }

    // Provenance check: descriptor must match an active substrate-issued grant.
    unsafe {
        let registry = core::ptr::addr_of!(CAPABILITY_REGISTRY);
        for i in 0..MAX_CAPABILITY_GRANTS {
            let grant = &(*registry)[i];
            if grant.active
                && grant.kind == desc.kind
                && grant.instance == desc.instance
                && grant.nonce == desc.nonce
            {
                return true;
            }
        }
    }
    false
}

/// Boot-provisioned, read-only PCI segment-0/bus-0 capability for the first
/// driver witness. Device recognition remains in generated WSM.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn wsm_pci_config_capability(context: *mut RuntimeContext) -> Word {
    if context.is_null() {
        loop {
            core::hint::spin_loop();
        }
    }
    init_pci_config_grant()
}

/// Perform one bounded PCI configuration mechanism-1 read. This function
/// knows ranges and privilege, not virtio identity or driver policy.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn wsm_pci_config_read16(
    context: *mut RuntimeContext,
    capability: Word,
    bus: Word,
    device: Word,
    function: Word,
    offset: Word,
) -> Word {
    let (Some(0), Some(device), Some(function), Some(offset)) = (
        wsm_os_target::decode_fixnum(bus),
        wsm_os_target::decode_fixnum(device),
        wsm_os_target::decode_fixnum(function),
        wsm_os_target::decode_fixnum(offset),
    ) else {
        unsafe {
            wsm_fail(
                context,
                wsm_os_target::ErrorCode::AbiViolation as u32,
                capability,
                0x5043_4902,
            )
        }
    };
    if !verify_capability_grant(capability, CapabilityKind::PciConfig, 0)
        || !(0..=31).contains(&device)
        || !(0..=7).contains(&function)
        || !(0..=254).contains(&offset)
        || offset % 2 != 0
    {
        unsafe {
            wsm_fail(
                context,
                wsm_os_target::ErrorCode::AbiViolation as u32,
                capability,
                0x5043_4903,
            )
        }
    }
    let address = 0x8000_0000_u32
        | ((device as u32) << 11)
        | ((function as u32) << 8)
        | ((offset as u32) & 0xfc);
    unsafe { outl(PCI_CONFIG_ADDRESS, address) };
    let value = unsafe { inl(PCI_CONFIG_DATA) };
    let shift = ((offset as u32) & 2) * 8;
    match wsm_os_target::encode_fixnum(((value >> shift) & 0xffff) as i64) {
        Some(value) => value,
        None => unsafe {
            wsm_fail(
                context,
                wsm_os_target::ErrorCode::AbiViolation as u32,
                capability,
                0x5043_4904,
            )
        },
    }
}

