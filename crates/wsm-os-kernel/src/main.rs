#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    serial_init();
    serial_write(b"WSM-OS PANIC schema=1 arch=x86_64 status=panic\n");
    qemu_exit(0x11)
}

const COM1: u16 = 0x3f8;

fn serial_init() {
    unsafe {
        outb(COM1 + 1, 0x00);
        outb(COM1 + 3, 0x80);
        outb(COM1, 0x03);
        outb(COM1 + 1, 0x00);
        outb(COM1 + 3, 0x03);
        outb(COM1 + 2, 0xc7);
        outb(COM1 + 4, 0x0b);
    }
}

fn serial_write(bytes: &[u8]) {
    for &byte in bytes {
        unsafe { outb(COM1, byte) };
    }
}

